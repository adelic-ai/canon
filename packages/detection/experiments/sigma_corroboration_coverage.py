r"""Sigma-corroboration coverage map — the honest per-detector spectrum, measured on the real corpus.

For each registered detector technique, how much does the *independent* deduped Sigma panel actually
corroborate? The answer is a spectrum, not a yes — and the negatives are the point: a detector that no
community rule corroborates is a recorded gap, not a silent pass. Run on real representative events
(OTRF Sysmon + flaws CloudTrail file00 + a representative Kerberos 4769), this writes the recorded
artifact `design/sigma_corroboration_coverage.md`.

Run: .venv/bin/python packages/detection/experiments/sigma_corroboration_coverage.py
"""

from __future__ import annotations

import json
from pathlib import Path

from detection.sigma_panel import corroboration_coverage, lsass_comsvcs_event
from detection.subgraph import load_sysmon_events

OTRF = Path.home() / "data/otrf-security-datasets/LSASS_campaign_03/lsass_campaign_03.json"
FLAWS00 = Path.home() / "data/flaws-cloudtrail/v1/flaws_cloudtrail00.json"
AWS = {"product": "aws", "service": "cloudtrail"}
SEC = {"product": "windows", "service": "security"}
OUT = Path(__file__).parents[3] / "design" / "sigma_corroboration_coverage.md"


def _flaws(predicate, limit=None):
    recs = json.load(open(FLAWS00)).get("Records", [])
    hits = [r for r in recs if predicate(r)]
    return hits[:limit] if limit else hits


def build_specs() -> list[dict]:
    from detection.cloudtrail import MANIPULATION_APIS

    comsvcs = lsass_comsvcs_event(load_sysmon_events(str(OTRF)))
    list_buckets = _flaws(lambda r: r.get("eventName") == "ListBuckets", limit=1)
    manip = _flaws(lambda r: r.get("eventName") in MANIPULATION_APIS)
    region = _flaws(lambda r: r.get("awsRegion") not in (None, "us-east-1"), limit=1)
    # representative Kerberos 4769 RC4 service-ticket request in our Splunk-CIM schema
    krb_4769 = {"EventID": 4769, "Service_Name": "MSSQLSvc/db.contoso.com",
                "Ticket_Encryption_Type": "0x17", "Account_Name": "svc_app"}

    return [
        {"technique": "T1003.001", "logsource": "process_access", "events": comsvcs,
         "note": "the comsvcs LSASS dump — corroborated by the dedicated CallTrace rule"},
        {"technique": "T1580", "logsource": AWS, "events": list_buckets,
         "note": "S3 enumeration — aws_enum_buckets fires on the native ListBuckets event"},
        {"technique": "T1098", "logsource": AWS, "events": manip,
         "note": "SigmaHQ's account-manip rules cover other IAM ops (UpdateLoginProfile, Route53) "
                 "than our CreateUser/AccessKey family — evaluated, no overlap"},
        {"technique": "T1496", "logsource": AWS, "events": region,
         "note": "region-sweep — SigmaHQ's T1496 rules are azure/zeek, none aws/cloudtrail"},
        {"technique": "T1558.003", "logsource": SEC, "events": krb_4769,
         "note": "the evaluable security rules target tooling artifacts (Rubeus EID 4611), not the "
                 "behavioral 4769 RC4 fan-out our detector flags — a detection-model gap, not just naming"},
        {"technique": "T1550.003", "logsource": SEC, "events": krb_4769,
         "note": "pass-the-ticket — no evaluable windows/security rule (SigmaHQ's are process_creation)"},
        {"technique": "T1110.003", "logsource": SEC, "events": {"EventID": 4625},
         "note": "password spraying — no SigmaHQ rule tagged attack.t1110.003 at all"},
    ]


def main() -> None:
    rows = corroboration_coverage(build_specs())

    print("=== Sigma-corroboration coverage map (real corpus) ===\n")
    hdr = f"{'technique':12} {'logsource':22} {'tagged':>6} {'rel':>4} {'cls':>4} {'eval':>4} {'votes':>5}  category"
    print(hdr)
    print("-" * len(hdr))
    for r in rows:
        print(f"{r['technique']:12} {r['logsource'][:22]:22} {r['tagged']:>6} {r['relevant']:>4} "
              f"{r['classes']:>4} {r['evaluated']:>4} {r['votes']:>5}  {r['category']}")

    lines = ["# Sigma-corroboration coverage map",
             "",
             "How much does the *independent* deduped Sigma panel actually corroborate each registered",
             "detector? Measured on real representative events (OTRF Sysmon + flaws CloudTrail). The",
             "negatives are recorded data, not silence — `no-overlap`/`not-evaluable`/`no-same-logsource`",
             "each name a distinct, honest reason the external panel does not confirm.",
             "",
             "Generated by `packages/detection/experiments/sigma_corroboration_coverage.py`.",
             ""]
    for r in rows:
        fired = ", ".join(r["fired"]) if r["fired"] else "—"
        lines += [f"## {r['technique']} — {r['category']}",
                  f"- logsource: `{r['logsource']}`",
                  f"- panel: {r['tagged']} tagged → {r['relevant']} same-logsource → {r['classes']} deduped "
                  f"classes → {r['evaluated']} evaluable → {r['votes']} fired",
                  f"- fired: {fired}",
                  f"- note: {r['note']}",
                  ""]
    OUT.write_text("\n".join(lines))
    print(f"\nwrote {OUT.relative_to(Path.home())}")


if __name__ == "__main__":
    main()
